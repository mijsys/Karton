const appOrder = ["overview", "roadmap", "gallery", "kartonos"];
const appShort = {
  overview: "OV",
  roadmap: "RM",
  gallery: "GL",
  kartonos: "OS"
};

const appTitleKey = {
  overview: "appOverviewTitle",
  roadmap: "appRoadmapTitle",
  gallery: "appGalleryTitle",
  kartonos: "appKartonOSTitle"
};

const html = document.documentElement;
const storedLanguage = localStorage.getItem("karton-site-language");
const browserLanguage = navigator.language ? navigator.language.slice(0, 2) : "en";
let currentLanguage = translations[storedLanguage] ? storedLanguage : translations[browserLanguage] ? browserLanguage : "en";

const storedTheme = localStorage.getItem("karton-site-theme");
let currentTheme = storedTheme === "light" || storedTheme === "dark"
  ? storedTheme
  : window.matchMedia("(prefers-color-scheme: dark)").matches
    ? "dark"
    : "light";

let currentVersion = "0.1";
let zTop = 10;

const runningApps = new Set(appOrder);
const minimizedApps = new Set();

const windows = new Map();
document.querySelectorAll(".app-window").forEach((el) => {
  windows.set(el.dataset.app, el);
});

const runningContainer = document.getElementById("running-apps");
const workspaceEmpty = document.getElementById("workspace-empty");
const launcherPanel = document.getElementById("launcher-panel");
const quickPanel = document.getElementById("quick-panel");

function applyTheme(theme) {
  html.dataset.theme = theme;
  document.querySelectorAll(".theme-switcher button").forEach((button) => {
    button.classList.toggle("is-active", button.dataset.theme === theme);
  });
}

function applyLanguage(language) {
  const dictionary = translations[language] || translations.en;
  html.lang = language;

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.dataset.i18n;
    if (dictionary[key]) {
      node.textContent = dictionary[key];
    }
  });

  document.querySelectorAll(".lang-switcher button").forEach((button) => {
    button.classList.toggle("is-active", button.dataset.lang === language);
  });

  updateClock();
  updateRelease();
  renderGallery();
  renderRunningApps();
}

function updateClock() {
  const now = new Date();
  const time = new Intl.DateTimeFormat(currentLanguage, {
    hour: "2-digit",
    minute: "2-digit"
  }).format(now);

  const date = new Intl.DateTimeFormat(currentLanguage, {
    weekday: "short",
    year: "numeric",
    month: "2-digit",
    day: "2-digit"
  }).format(now);

  const timeNode = document.getElementById("panel-time");
  const dateNode = document.getElementById("panel-date");
  if (timeNode) {
    timeNode.textContent = time;
  }
  if (dateNode) {
    dateNode.textContent = date;
  }
}

function updateRelease() {
  const releaseTitle = document.getElementById("release-title");
  const releaseCopy = document.getElementById("release-copy");
  if (!releaseTitle || !releaseCopy) {
    return;
  }

  releaseTitle.textContent = currentVersion;
  const copySet = releaseData[currentLanguage] || releaseData.en;
  releaseCopy.textContent = copySet[currentVersion] || "";
}

function renderGallery() {
  const galleryGrid = document.getElementById("gallery-grid");
  const template = document.getElementById("gallery-card-template");
  if (!galleryGrid || !template) {
    return;
  }

  galleryGrid.textContent = "";
  const items = galleryData[currentVersion] || [];

  if (!items.length) {
    const empty = document.createElement("div");
    empty.className = "gallery-empty";
    empty.textContent = (translations[currentLanguage] || translations.en).galleryEmpty;
    galleryGrid.appendChild(empty);
    return;
  }

  items.forEach((item) => {
    const fragment = template.content.cloneNode(true);
    const img = fragment.querySelector("img");
    const title = fragment.querySelector(".gallery-title");
    const caption = fragment.querySelector(".gallery-caption");

    img.src = item.src;
    img.alt = item.title[currentLanguage] || item.title.en;
    title.textContent = item.title[currentLanguage] || item.title.en;
    caption.textContent = item.caption[currentLanguage] || item.caption.en;

    galleryGrid.appendChild(fragment);
  });
}

function bringToFront(app) {
  const win = windows.get(app);
  if (!win) {
    return;
  }

  zTop += 1;
  win.style.zIndex = String(zTop);
  renderRunningApps(app);
}

function updateWorkspaceEmpty() {
  const hasVisible = appOrder.some((app) => runningApps.has(app) && !minimizedApps.has(app));
  workspaceEmpty.hidden = hasVisible;
}

function openApp(app) {
  const win = windows.get(app);
  if (!win) {
    return;
  }

  runningApps.add(app);
  minimizedApps.delete(app);
  win.classList.remove("is-minimized", "is-closed");
  bringToFront(app);
  updateWorkspaceEmpty();
}

function minimizeApp(app) {
  const win = windows.get(app);
  if (!win || !runningApps.has(app)) {
    return;
  }

  minimizedApps.add(app);
  win.classList.add("is-minimized");
  updateWorkspaceEmpty();
  renderRunningApps();
}

function closeApp(app) {
  const win = windows.get(app);
  if (!win) {
    return;
  }

  runningApps.delete(app);
  minimizedApps.delete(app);
  win.classList.add("is-closed");
  updateWorkspaceEmpty();
  renderRunningApps();
}

function renderRunningApps(activeApp) {
  runningContainer.textContent = "";

  appOrder.forEach((app) => {
    if (!runningApps.has(app)) {
      return;
    }

    const button = document.createElement("button");
    button.type = "button";
    button.className = "dock-app";

    if (activeApp && activeApp === app) {
      button.classList.add("is-active");
    }

    button.dataset.app = app;
    button.title = (translations[currentLanguage] || translations.en)[appTitleKey[app]] || app;

    const label = document.createElement("span");
    label.textContent = appShort[app] || app.slice(0, 2).toUpperCase();
    button.appendChild(label);

    button.addEventListener("click", () => {
      openApp(app);
    });

    runningContainer.appendChild(button);
  });
}

function togglePanel(panel) {
  if (!panel) {
    return;
  }

  const isOpen = !panel.hidden;
  launcherPanel.hidden = true;
  quickPanel.hidden = true;

  if (!isOpen) {
    panel.hidden = false;
  }
}

function bindGlobalActions() {
  document.querySelectorAll("[data-action='toggle-launcher']").forEach((button) => {
    button.addEventListener("click", () => {
      togglePanel(launcherPanel);
    });
  });

  document.querySelectorAll("[data-action='toggle-quick']").forEach((button) => {
    button.addEventListener("click", () => {
      togglePanel(quickPanel);
    });
  });

  document.querySelectorAll(".launcher-app").forEach((button) => {
    button.addEventListener("click", () => {
      const app = button.dataset.app;
      openApp(app);
      launcherPanel.hidden = true;
    });
  });

  document.querySelectorAll(".win-btn").forEach((button) => {
    button.addEventListener("click", (event) => {
      event.stopPropagation();
      const app = button.dataset.app;
      const action = button.dataset.action;
      if (action === "minimize") {
        minimizeApp(app);
      }
      if (action === "close") {
        closeApp(app);
      }
    });
  });

  document.querySelectorAll(".window-bar").forEach((bar) => {
    bar.addEventListener("click", () => {
      const host = bar.closest(".app-window");
      if (host) {
        bringToFront(host.dataset.app);
      }
    });
  });

  document.querySelectorAll(".timeline-item").forEach((button) => {
    button.addEventListener("click", () => {
      currentVersion = button.dataset.version;
      document.querySelectorAll(".timeline-item").forEach((item) => {
        const isActive = item === button;
        item.classList.toggle("is-active", isActive);
        item.setAttribute("aria-selected", String(isActive));
      });
      updateRelease();
      renderGallery();
    });
  });

  document.querySelectorAll(".theme-switcher button").forEach((button) => {
    button.addEventListener("click", () => {
      currentTheme = button.dataset.theme;
      localStorage.setItem("karton-site-theme", currentTheme);
      applyTheme(currentTheme);
    });
  });

  document.querySelectorAll(".lang-switcher button").forEach((button) => {
    button.addEventListener("click", () => {
      currentLanguage = button.dataset.lang;
      localStorage.setItem("karton-site-language", currentLanguage);
      applyLanguage(currentLanguage);
    });
  });

  document.addEventListener("click", (event) => {
    const target = event.target;
    const inLauncher = launcherPanel.contains(target);
    const inQuick = quickPanel.contains(target);
    const launchToggle = target.closest("[data-action='toggle-launcher']");
    const quickToggle = target.closest("[data-action='toggle-quick']");

    if (!inLauncher && !launchToggle) {
      launcherPanel.hidden = true;
    }

    if (!inQuick && !quickToggle) {
      quickPanel.hidden = true;
    }
  });
}

function initWindows() {
  appOrder.forEach((app, index) => {
    const win = windows.get(app);
    if (!win) {
      return;
    }

    win.style.zIndex = String(zTop + index);
  });

  zTop += appOrder.length;
}

applyTheme(currentTheme);
applyLanguage(currentLanguage);
initWindows();
bindGlobalActions();
renderRunningApps("overview");
updateWorkspaceEmpty();
updateClock();
setInterval(updateClock, 1000);

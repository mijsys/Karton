const defaultLanguage = "en";
const page = document.body.dataset.page;
const html = document.documentElement;
const storedLanguage = localStorage.getItem("karton-site-language");
const browserLanguage = navigator.language ? navigator.language.slice(0, 2) : defaultLanguage;
let currentLanguage = translations[storedLanguage] ? storedLanguage : translations[browserLanguage] ? browserLanguage : defaultLanguage;
let currentVersion = "0.1";

function translatePage() {
  const dictionary = translations[currentLanguage];

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.dataset.i18n;

    if (dictionary[key]) {
      node.textContent = dictionary[key];
    }
  });

  html.lang = currentLanguage;
  document.querySelectorAll(".lang-switcher button").forEach((button) => {
    button.classList.toggle("is-active", button.dataset.lang === currentLanguage);
  });

  if (page === "home") {
    updateReleaseCopy();
    renderGallery();
  }
}

function updateReleaseCopy() {
  const title = document.getElementById("release-title");
  const copy = document.getElementById("release-copy");

  if (!title || !copy) {
    return;
  }

  title.textContent = currentVersion;
  copy.textContent = releaseData[currentLanguage][currentVersion];
}

function renderGallery() {
  const galleryGrid = document.getElementById("gallery-grid");
  const template = document.getElementById("gallery-card-template");

  if (!galleryGrid || !template) {
    return;
  }

  galleryGrid.textContent = "";

  const items = galleryData[currentVersion] || [];

  if (!items.length) {
    const empty = document.createElement("div");
    empty.className = "gallery-empty";
    empty.textContent = translations[currentLanguage].galleryEmpty;
    galleryGrid.appendChild(empty);
    return;
  }

  items.forEach((item) => {
    const fragment = template.content.cloneNode(true);
    const image = fragment.querySelector("img");
    const title = fragment.querySelector(".gallery-title");
    const caption = fragment.querySelector(".gallery-caption");

    image.src = item.src;
    image.alt = item.title[currentLanguage];
    title.textContent = item.title[currentLanguage];
    caption.textContent = item.caption[currentLanguage];

    galleryGrid.appendChild(fragment);
  });
}

function bindLanguageSwitcher() {
  document.querySelectorAll(".lang-switcher button").forEach((button) => {
    button.addEventListener("click", () => {
      currentLanguage = button.dataset.lang;
      localStorage.setItem("karton-site-language", currentLanguage);
      translatePage();
    });
  });
}

function bindTimeline() {
  document.querySelectorAll(".timeline-item").forEach((button) => {
    button.addEventListener("click", () => {
      currentVersion = button.dataset.version;
      document.querySelectorAll(".timeline-item").forEach((item) => {
        const isActive = item === button;
        item.classList.toggle("is-active", isActive);
        item.setAttribute("aria-selected", String(isActive));
      });
      updateReleaseCopy();
      renderGallery();
    });
  });
}

bindLanguageSwitcher();
bindTimeline();
translatePage();